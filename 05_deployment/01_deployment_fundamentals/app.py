# Development - среда разработки, используется для тестирования и отладки приложения.
# Testing/staging - среда тестирования, используется для проверки функциональности приложения перед его развертыванием в production.
# Production - среда продакшн, используется для развертывания и эксплуатации приложения в реальных условиях.
# Example:
# В Development меняешь Python-код, 
# В Testing/staging проверяешь API и предсказания модели,
# В Production пользователи отправляют запросы к API и получают предсказания модели.
# Архитектурное правило: то что работает на твоем компьютере, не обязательно будет работать в Production. Поэтому нужно тестировать и проверять приложение в разных средах.
